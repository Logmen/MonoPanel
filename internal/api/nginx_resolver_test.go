package api

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// nginx's resolver (OCSP stapling) comes from the host's resolv.conf: the
// template's 127.0.0.53 is systemd-resolved's stub, which EL does not run,
// and nginx's error log there filled with "send() failed (111) while
// resolving". The template's public server stays behind the host's, its
// parameters too; Ubuntu's stub gives the line the template has.
func TestSSLSnippetResolverFromResolvConf(t *testing.T) {
	f := newSiteFixture(t)
	snippets, err := f.s.render.Snippets("nginx/snippets")
	if err != nil {
		t.Fatal(err)
	}
	tmpl := snippets["ssl.conf"]
	const stock = "resolver 127.0.0.53 1.1.1.1 valid=300s;"
	if !strings.Contains(tmpl, stock+"\n") {
		t.Fatalf("the template's resolver line changed:\n%s", tmpl)
	}
	for _, c := range []struct{ name, resolv, want string }{
		{"ubuntu", "# This is /run/systemd/resolve/stub-resolv.conf\nnameserver 127.0.0.53\noptions edns0 trust-ad\nsearch .\n", stock},
		{"el", "# Generated by NetworkManager\nsearch example.lan\nnameserver 10.0.0.2\nnameserver 2001:db8::53\nnameserver fe80::1%eth0\nnameserver 10.0.0.2\n", "resolver 10.0.0.2 [2001:db8::53] 1.1.1.1 valid=300s;"},
		{"public already", "nameserver 1.1.1.1\nnameserver 8.8.8.8\n", "resolver 1.1.1.1 8.8.8.8 valid=300s;"},
		{"none", "", stock},
		{"junk", "nameserver ;include /etc/shadow\nnameserver\n#nameserver 10.9.9.9\n", stock},
	} {
		got := sslSnippet(tmpl, c.resolv)
		if !strings.Contains(got, c.want+"\n") || strings.Count(got, "resolver ") != 1 || !strings.Contains(got, "resolver_timeout 5s;") {
			t.Errorf("%s: want %q in\n%s", c.name, c.want, got)
		}
	}

	// What the panel writes to nginx takes the host's file.
	f.s.resolvConf = filepath.Join(t.TempDir(), "resolv.conf")
	if err := os.WriteFile(f.s.resolvConf, []byte("nameserver 192.0.2.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	files, _, err := f.s.nginxGlobalFiles(f.ctx)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, file := range files {
		if strings.HasSuffix(file.Path, "/monopanel/snippets/ssl.conf") {
			found = true
			if !strings.Contains(file.Content, "resolver 192.0.2.53 1.1.1.1 valid=300s;\n") {
				t.Errorf("ssl.conf written:\n%s", file.Content)
			}
		}
	}
	if !found {
		t.Error("no ssl.conf among nginx's files")
	}
}
