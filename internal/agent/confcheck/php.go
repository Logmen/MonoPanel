// PHP. The php-fpm master runs as root: it loads every extension of its
// ini files, runs opcache's preload, writes its own log and pid file, opens
// the pools' slow logs and access logs, and creates their sockets. The CLI
// runs as root too — Debian's sessionclean, pecl and pear, composer and
// cron scripts an administrator starts — and reads the CLI ini directory
// (on Remi the one php.d it shares with FPM). Pools run as their account,
// so a pool's PHP settings are the account's business; who the pool runs
// as, and what its master opens, are not.

var phpDirs = []string{"/etc/php", "/etc/opt/remi"}

func isPHP(p string) bool { return underAny(p, phpDirs...) }

func checkPHP(c *checker, p string, content []byte) error {
	if want, ok := IdlePool(c.l.RunDir, p); ok {
		if string(content) == want {
			return nil
		}
		return notAllowed("writing "+p, "the distribution's own pool of the branch holds the panel's idle pool and nothing else: as the web server's account (www-data, apache) its PHP reaches the root master's run and log directories")
	}
	switch {
	case strings.HasSuffix(p, ".ini"):
		return checkPHPIni(content)
	case path.Base(p) == "php-fpm.conf":
		return c.checkFPM(p, content, true)
	case strings.HasSuffix(p, ".conf"):
		return c.checkFPM(p, content, false)
	}
	return notAllowed("writing "+p, "the panel writes *.ini and php-fpm *.conf files there; PHP and its tools read others (pear.conf) as root")
}

// The distributions' own pool. The php-fpm package of every branch ships
// one, [www]: Debian's and Ubuntu's (Sury's, Ubuntu's own, the builds of
// ppa:ondrej/php that panels up to 0.8.19 installed on Ubuntu)
// pool.d/www.conf runs PHP as www-data on /run/php/php<v>-fpm.sock, in the
// directory www-data owns where the root master also writes its pid file
// and chowns the socket by path; Remi's php-fpm.d/www.conf runs it as
// apache, with nginx allowed on the socket (listen.acl_users), and apache
// owns the directory of the root master's log. PHP as either account
// reaches root through those files. The sites have pools of their own; the
// distribution's stays, since a php-fpm master does not start without a
// pool and Debian's unit reads www.conf after the start (its socket
// helper), but idle: as nobody, on a socket in the root-owned
// RunDir/php that root alone may connect to, starting no process until
// something does. Package upgrades keep the file (dpkg's conffile, rpm's
// %config(noreplace)). The panel writes it once per branch; an
// administrator's own pool there afterwards is theirs (the doctor names
// it), as nothing the panel writes can reach it: fastcgi_pass names the
// panel's sockets only, and no Apache's children run as www-data. Whatever
// the panel writes at that path is the idle pool and nothing else.

var (
	debianPoolRe = regexp.MustCompile(`^/etc/php/([0-9]+\.[0-9]+)/fpm/pool\.d/www\.conf$`)
	remiPoolRe   = regexp.MustCompile(`^/etc/opt/remi/php([0-9])([0-9])/php-fpm\.d/www\.conf$`)
)

// idlePoolHeads are the first lines of the idle pool, today's first. The
// development builds of 0.9.0 wrote the second one, from before the panel
// made the pool idle once a branch and left it alone afterwards
// (php_pools.go): it says the panel writes the file again whenever it
// starts, which the release does not do. The comment is all they differ in.
var idlePoolHeads = []string{
	"; Generated by MonoPanel once: the panel writes this file again only when it is\n" +
		"; missing, and leaves your changes as they are (mp doctor names them).\n",
	"; Generated by MonoPanel - do not edit: the panel writes this file again at its start.\n",
}

// IdlePool is the content of p, the distribution's pool file of a branch
// (www.conf in Debian's or Remi's pool directory), as the panel writes it:
// the pool [www] runs as nobody (group nogroup on Debian, nobody on EL) on
// runDir/php/.idle-<branch>.sock — a name no site's socket can have, as a
// domain does not start with a dot — owned by root, mode 0600, and starts
// at most one process, on demand. ok is false for any other path and for a
// runDir that is no plain absolute path. Check accepts nothing else at p.
func IdlePool(runDir, p string) (content string, ok bool) {
	body, ok := idlePoolBody(runDir, p)
	if !ok {
		return "", false
	}
	return idlePoolHeads[0] + body, true
}

// EarlierIdlePools are the texts earlier builds wrote at p as the idle
// pool: IdlePool's pool under a comment of their own (idlePoolHeads). Check
// accepts none of them at p; the API takes a pool file that holds one for
// the idle pool still, and writes IdlePool's text over it.
func EarlierIdlePools(runDir, p string) []string {
	body, ok := idlePoolBody(runDir, p)
	if !ok {
		return nil
	}
	out := make([]string, 0, len(idlePoolHeads)-1)
	for _, head := range idlePoolHeads[1:] {
		out = append(out, head+body)
	}
	return out
}

// idlePoolBody is the idle pool of p below its first comment line.
func idlePoolBody(runDir, p string) (string, bool) {
	var branch, group string
	if m := debianPoolRe.FindStringSubmatch(p); m != nil {
		branch, group = m[1], "nogroup"
	} else if m := remiPoolRe.FindStringSubmatch(p); m != nil {
		branch, group = m[1]+"."+m[2], "nobody"
	} else {
		return "", false
	}
	runDir = path.Clean(runDir)
	if !plainPathRe.MatchString(runDir) || hasDotDot(runDir) {
		return "", false
	}
	return "; The distribution's own pool of PHP " + branch + ", kept idle: php-fpm starts no master\n" +
		"; without a pool, and the sites run in pools of their own (a file each in this\n" +
		"; directory). It runs as nobody, nothing but root may connect to its socket, and\n" +
		"; it starts no process until something does.\n" +
		"[www]\n" +
		"user = nobody\n" +
		"group = " + group + "\n" +
		"listen = " + path.Join(runDir, "php", ".idle-"+branch+".sock") + "\n" +
		"listen.owner = root\n" +
		"listen.group = root\n" +
		"listen.mode = 0600\n" +
		"pm = ondemand\n" +
		"pm.max_children = 1\n" +
		"pm.process_idle_timeout = 10s\n", true
}

type iniEntry struct {
	line    int
	section string
	key     string // as written
	base    string // lower-case, without [offset]
	offset  string // php_value[offset], env[offset]
	value   string // unquoted, without a trailing comment
	raw     string // the value as written
	hasEq   bool
}

// parsePHPIni reads the ini syntax of PHP and php-fpm line by line. A
// quoted value that spans lines is read as separate lines here: each of
// them is checked as if it were a directive, which refuses more, never less.
func parsePHPIni(content []byte) ([]iniEntry, error) {
	lines, err := textLines(content)
	if err != nil {
		return nil, err
	}
	var out []iniEntry
	section := ""
	for i, raw := range lines {
		n := i + 1
		// The scanner's blanks are spaces and tabs (TABS_AND_SPACES).
		s := trimBlanks(raw)
		if s == "" || s[0] == ';' || s[0] == '#' {
			continue
		}
		if s[0] == '[' {
			end := strings.IndexByte(s, ']')
			if end < 0 {
				return nil, unreadable(n, "unterminated section %q", s)
			}
			if tail := trimBlanks(s[end+1:]); tail != "" && tail[0] != ';' {
				return nil, unreadable(n, "text after the section %q", s)
			}
			section = trimBlanks(s[1:end])
			continue
		}
		e := iniEntry{line: n, section: section}
		key, val, hasEq := strings.Cut(s, "=")
		e.key, e.hasEq = trimBlanks(key), hasEq
		e.raw = trimBlanks(val)
		e.value = iniValue(e.raw)
		e.base = strings.ToLower(e.key)
		if i := strings.IndexByte(e.key, '['); i >= 0 {
			if !strings.HasSuffix(e.key, "]") {
				return nil, unreadable(n, "bad key %q", e.key)
			}
			// The scanner eats the blanks around the offset (and before the
			// "["); a quoted or ${} offset is a string PHP builds, which this
			// check does not.
			e.offset = trimBlanks(e.key[i+1 : len(e.key)-1])
			if strings.ContainsAny(e.offset, "\"'$[]") {
				return nil, unreadable(n, "the offset of %q is not a plain name", e.key)
			}
			e.base = strings.ToLower(trimBlanks(e.key[:i]))
		}
		out = append(out, e)
	}
	return out, nil
}

// iniValue is the value without its quotes and trailing comment.
func iniValue(raw string) string {
	if raw == "" {
		return ""
	}
	if q := raw[0]; q == '"' || q == '\'' {
		if end := strings.IndexByte(raw[1:], q); end >= 0 {
			return raw[1 : 1+end]
		}
		return raw
	}
	if i := strings.IndexByte(raw, ';'); i >= 0 {
		raw = raw[:i]
	}
	return trimBlanks(raw)
}

// iniToken is a value that is one plain token: unquoted without blanks,
// quotes, ${...} or the ini operators, or one quoted string without escapes
// and expansions, either followed by nothing but a comment. PHP's ini
// grammar joins several strings and expands ${...} inside double quotes, so
// a value the checks below vouch for has to be one the check reads exactly
// as PHP does.
func iniToken(raw string) (string, bool) {
	if raw == "" {
		return "", false
	}
	if q := raw[0]; q == '"' || q == '\'' {
		end := strings.IndexByte(raw[1:], q)
		if end < 0 {
			return "", false
		}
		v := raw[1 : 1+end]
		if rest := trimBlanks(raw[2+end:]); rest != "" && rest[0] != ';' {
			return "", false
		}
		if v == "" || strings.ContainsAny(v, "\\\"'$\n") {
			return "", false
		}
		return v, true
	}
	if i := strings.IndexByte(raw, ';'); i >= 0 {
		raw = raw[:i]
	}
	v := trimBlanks(raw)
	if v == "" || strings.ContainsAny(v, " \t\"'$&|^~!(){}[]=\\") {
		return "", false
	}
	return v, true
}

