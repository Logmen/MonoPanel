// Everything the API writes through config/apply passes, on the path it
// writes it to: the templates rendered with the models the API builds
// (internal/api: stack.go, ops_sites.go, ops_mail.go, ops_php.go, …), and
// the text the API builds in Go, copied from its call sites.

var presets = []string{"nginx/presets/wordpress.conf.tmpl", "nginx/presets/joomla.conf.tmpl", "nginx/presets/bitrix.conf.tmpl", "nginx/presets/opencart.conf.tmpl"}

func renderT(t *testing.T, tmpl string, data any) string {
	t.Helper()
	out, err := render.New("").RenderSet(tmpl, data, presets...)
	if err != nil {
		t.Fatalf("render %s: %v", tmpl, err)
	}
	return out
}

// site is a site the way jobSiteApply hands it to the templates.
func site(mode string, edit func(*render.Site)) render.Site {
	s := render.Site{
		Domain: "example.com", Aliases: []string{"www.example.com"}, Mode: mode, IP: "203.0.113.10",
		RedirectWWW: "none", Docroot: "/var/www/alex/data/www/example.com", LogDir: "/var/log/monopanel/sites/alex",
		IncludeDir: "monopanel/sites/example.com.d", ClientMaxBodySize: "64m", ApacheBackend: "127.100.3.233:81",
		ApacheBackendConf: "monopanel/apache/alex.conf", FPMSocket: "/run/monopanel/php/example.com.sock", ProxyTimeout: 150,
	}
	if edit != nil {
		edit(&s)
	}
	return s
}

func tls(s *render.Site) {
	s.TLS, s.HTTP2, s.HTTP3, s.RedirectHTTPS, s.HSTS = true, true, true, true, true
	s.CertPath, s.KeyPath = "/var/lib/monopanel/certs/example.com/fullchain.pem", "/var/lib/monopanel/certs/example.com/privkey.pem"
}

