// chmods sets modes as chmod(2) takes them, the sticky and setgid bits
// included.
func chmods(t *testing.T, modes map[string]uint32) {
	t.Helper()
	for p, m := range modes {
		if err := unix.Chmod(p, m); err != nil {
			t.Fatal(err)
		}
	}
}

// mountUnit is the unit the API writes for the shared folder bound at where.
func (h *shareHost) mountUnit(where string) (name, content string) {
	return mountUnitName(where), "# Generated by MonoPanel: shared folder of shop.example.com for guest\n[Unit]\nDescription=MonoPanel shared folder shop.example.com/kaspy for guest\nRequiresMountsFor=" + filepath.Dir(h.site) +
		"\n\n[Mount]\nWhat=" + h.site + "\nWhere=" + where + "\nType=none\nOptions=bind\n\n[Install]\nWantedBy=multi-user.target\n"
}

// placeUnit writes the unit of where into the unit directory as the agent
// would have: a shared folder the panel set up earlier.
func (h *shareHost) placeUnit(t *testing.T, where string) string {
	t.Helper()
	name, content := h.mountUnit(where)
	if err := os.WriteFile(filepath.Join(h.s.unitDir, name), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return name
}

// pretendOwners makes directories look like other accounts' to the mount
// point checks: a test cannot give a directory away.
func pretendOwners(t *testing.T, owners map[string]uint32) {
	t.Helper()
	old := mountOwner
	mountOwner = func(dir string, st *unix.Stat_t) uint32 {
		if uid, ok := owners[dir]; ok {
			return uid
		}
		return st.Uid
	}
	t.Cleanup(func() { mountOwner = old })
}

// otherAccount is a real account that is neither root nor the test's user:
// the guard refuses a change to it before the agent would try the chown it
// may not make.
func otherAccount(t *testing.T) string {
	t.Helper()
	u, err := user.Lookup("nobody")
	if err != nil || u.Uid == "0" || u.Uid == strconv.Itoa(os.Getuid()) {
		t.Skip("no account nobody to hand directories to")
	}
	return "nobody"
}

func setfacl(t *testing.T, args ...string) {
	t.Helper()
	if _, err := exec.LookPath("setfacl"); err != nil {
		t.Skip("setfacl is not installed")
	}
	if out, err := exec.Command("setfacl", args...).CombinedOutput(); err != nil {
		if strings.Contains(string(out), "Operation not supported") {
			t.Skip("no ACLs on this file system")
		}
		t.Fatalf("setfacl %v: %v %s", args, err, out)
	}
}

// A shared folder is bound only when every directory from the web root down
// to the mount point is root's and nobody else may write to it: in the
// root-owned home of an SFTP-only guest, in .shares for a guest with a
// shell. A home the guest owns, a symlink on the way, a directory its group
// or an ACL lets others write to — refused, nothing bound, nothing recorded.
func TestMountPointMustBeRootsAlone(t *testing.T) {
	type setup func(t *testing.T, h *shareHost) (where string)
	inHome := func(t *testing.T, h *shareHost) string {
		where := filepath.Join(h.home, "kaspy")
		mkdirs(t, where)
		return where
	}
	inShares := func(t *testing.T, h *shareHost) string {
		where := filepath.Join(h.shares, "guest", "kaspy")
		mkdirs(t, where)
		chmods(t, map[string]uint32{h.shares: 0o711, filepath.Dir(where): 0o750})
		return where
	}
	for _, c := range []struct {
		name  string
		setup setup
		ok    bool
		why   string
	}{
		{"sftp home of root", inHome, true, ""},
		{"shares directory of root", inShares, true, ""},
		{"sticky shares directory", func(t *testing.T, h *shareHost) string {
			where := inShares(t, h)
			chmods(t, map[string]uint32{h.shares: 0o1777})
			return where
		}, true, ""},
		{"home of the guest", func(t *testing.T, h *shareHost) string {
			where := inHome(t, h)
			pretendOwners(t, map[string]uint32{h.home: 1500})
			return where
		}, false, "belongs to uid 1500"},
		{"shares directory of the guest", func(t *testing.T, h *shareHost) string {
			where := inShares(t, h)
			pretendOwners(t, map[string]uint32{filepath.Dir(where): 1500})
			return where
		}, false, "belongs to uid 1500"},
		{"mount point of the guest", func(t *testing.T, h *shareHost) string {
			where := inHome(t, h)
			pretendOwners(t, map[string]uint32{where: 1500})
			return where
		}, false, "belongs to uid 1500"},
		{"home writable by its group", func(t *testing.T, h *shareHost) string {
			where := inHome(t, h)
			chmods(t, map[string]uint32{h.home: 0o770})
			return where
		}, false, "writable by the group"},
		{"shares writable by everyone", func(t *testing.T, h *shareHost) string {
			where := inShares(t, h)
			chmods(t, map[string]uint32{h.shares: 0o777})
			return where
		}, false, "writable by everyone"},
		{"symlink as mount point", func(t *testing.T, h *shareHost) string {
			where := filepath.Join(h.home, "kaspy")
			if err := os.Symlink(t.TempDir(), where); err != nil {
				t.Fatal(err)
			}
			return where
		}, false, "symlink"},
		{"symlink on the way", func(t *testing.T, h *shareHost) string {
			elsewhere := t.TempDir()
			mkdirs(t, filepath.Join(elsewhere, "kaspy"), h.shares)
			if err := os.Symlink(elsewhere, filepath.Join(h.shares, "guest")); err != nil {
				t.Fatal(err)
			}
			return filepath.Join(h.shares, "guest", "kaspy")
		}, false, "symlink"},
		{"ACL lets another write", func(t *testing.T, h *shareHost) string {
			where := inHome(t, h)
			setfacl(t, "-m", "u:nobody:rwx", h.home)
			return where
		}, false, "ACL"},
		{"mount point with entries of a restore", func(t *testing.T, h *shareHost) string {
			where := inHome(t, h)
			setfacl(t, "-m", "u:nobody:rwx", where)
			chmods(t, map[string]uint32{where: 0o755})
			return where
		}, true, ""},
		{"ACL held back by the mask", func(t *testing.T, h *shareHost) string {
			where := inHome(t, h)
			setfacl(t, "-m", "u:nobody:rwx", h.home)
			chmods(t, map[string]uint32{h.home: 0o750})
			return where
		}, false, "once the mask is recalculated"},
		{"no mount point yet", func(t *testing.T, h *shareHost) string {
			return filepath.Join(h.home, "kaspy")
		}, false, "does not exist"},
	} {
		t.Run(c.name, func(t *testing.T) {
			h := newShareHost(t)
			where := c.setup(t, h)
			res, err := h.bind(where)
			_, recorded := h.s.recordedOK(t, where)
			if c.ok {
				if err != nil || !res.Mounted || !res.Changed {
					t.Fatalf("bind: %+v %v", res, err)
				}
				if want := ino(t, h.site) + " on " + ino(t, where); len(h.binds) != 1 || h.binds[0] != want {
					t.Fatalf("binds %v, want %s", h.binds, want)
				}
				if !recorded {
					t.Fatal("the bound folder is not recorded")
				}
				return
			}
			if agentStatus(err) != http.StatusForbidden || !strings.Contains(err.Error(), c.why) {
				t.Fatalf("bind: %v, want 403 saying %q", err, c.why)
			}
			if len(h.binds) != 0 || recorded {
				t.Fatalf("a refused folder was bound %v or recorded %v", h.binds, recorded)
			}
		})
	}
}

// recordedOK reads the record of the shared folder at where.
func (s *Server) recordedOK(t *testing.T, where string) (string, bool) {
	t.Helper()
	recs, err := s.shareRecords()
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range recs {
		if r.Where == where {
			return r.What, true
		}
	}
	return "", false
}

// systemd mounts nothing below the web root on the agent's word: a mount
// unit names its folder by path, and the folder's owner may have swapped
// that path for a symlink by then. Starting, restarting, reloading or
// enabling one is refused — a unit an older panel or an administrator
// wrote as much as the units systemd shows for the agent's own binds — and
// so is its restart as a reload of config/apply or paths/remove; stop,
// disable and status pass.
func TestVetMountStartRefusesMountsBelowTheWebRoot(t *testing.T) {
	ctx := context.Background()
	h := newShareHost(t)
	mount := filepath.Join(h.home, "kaspy")
	mkdirs(t, mount)
	name := h.placeUnit(t, mount)
	for _, action := range []string{"start", "restart", "reload", "reload-or-restart", "enable"} {
		_, err := h.s.service(ctx, &ServiceRequest{Unit: name, Action: action})
		if agentStatus(err) != http.StatusForbidden || !strings.Contains(err.Error(), "binds the shared folders itself") {
			t.Fatalf("%s: %v, want 403", action, err)
		}
	}
	// without a unit file: what systemd shows for a bind of the agent's
	if err := h.s.vetMountStart(mountUnitName(filepath.Join(h.shares, "guest", "x")), "restart"); agentStatus(err) != http.StatusForbidden {
		t.Fatalf("the restart of a bind of the agent's: %v", err)
	}
	for _, action := range []string{"stop", "disable", "status"} {
		if err := h.s.vetMountStart(name, action); err != nil {
			t.Fatalf("%s must not be held back: %v", action, err)
		}
	}
	if _, err := h.s.applyConfigSet(ctx, &ApplyConfigSetRequest{Reload: []string{name}}); agentStatus(err) != http.StatusForbidden {
		t.Fatalf("config/apply reload: %v", err)
	}
	if _, err := h.s.removePaths(ctx, &RemovePathsRequest{Reload: []string{name}}); agentStatus(err) != http.StatusForbidden {
		t.Fatalf("paths/remove reload: %v", err)
	}
}

