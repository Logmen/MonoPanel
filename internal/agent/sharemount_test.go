// While a shared folder's unit exists, nothing the agent does hands a
// directory on the way to its mount point — the home of an SFTP-only guest,
// .shares and the guest's directory there, the mount point itself — to an
// account, lets others write to it, removes it or puts something else
// there: dirs/ensure, chown, user/ensure, user/remove, acl/set, acl/site,
// paths/remove, symlink/ensure, file/ensure, an archive's extraction. The
// same calls for another home go through.
func TestShareGuardKeepsTheWayRoots(t *testing.T) {
	ctx := context.Background()
	h := newShareHost(t)
	other := otherAccount(t)
	me := withMeAsClient(t, h.s)
	withAccounts(t, testAccount{me, strconv.Itoa(os.Getuid()), strconv.Itoa(os.Getgid()), filepath.Join(h.www, me), []string{me}},
		testAccount{"guest", "1500", "1500", h.home, []string{"guest", sftpGroup}})
	mount := filepath.Join(h.home, "kaspy")
	mkdirs(t, mount, filepath.Join(h.www, me))
	h.placeUnit(t, mount)
	bob := filepath.Join(h.www, "bob")
	conflict := func(what string, err error) {
		t.Helper()
		if agentStatus(err) != http.StatusConflict || !strings.Contains(err.Error(), "remove or move the shared folders of guest first") {
			t.Errorf("%s: %v, want 409", what, err)
		}
	}
	passes := func(what string, err error) {
		t.Helper()
		if err != nil {
			t.Errorf("%s: %v", what, err)
		}
	}

	// dirs/ensure: no other owner, no group or other write on the way; the
	// same spec again, a root's mode, the inside of the mount point and
	// another home are fine.
	_, err := h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: h.home, Mode: 0o710, Owner: other}}})
	conflict("the home to its account", err)
	_, err = h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: h.home, Mode: 0o770}}})
	conflict("the home writable by its group", err)
	_, err = h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: mount, Mode: 0o777}}})
	conflict("the mount point writable by everyone", err)
	_, err = h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: h.home, Mode: 0o750, Owner: me}}})
	passes("the home root's", err)
	_, err = h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: filepath.Join(mount, "sub"), Mode: 0o777}, {Path: bob, Mode: 0o777}}})
	passes("inside the folder and another home", err)
	if st, _ := os.Stat(h.home); st.Mode().Perm() != 0o750 {
		t.Fatalf("the home is %v now", st.Mode().Perm())
	}
	// a level made on the way gets the owner too: refused before it is made
	carol := filepath.Join(h.www, "carol")
	h.placeUnit(t, filepath.Join(carol, "x"))
	_, err = h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: filepath.Join(carol, "x", "y"), Mode: 0o750, Owner: other}}})
	if agentStatus(err) != http.StatusConflict {
		t.Errorf("a level made on the way: %v, want 409", err)
	}
	if _, err := os.Stat(carol); !errors.Is(err, os.ErrNotExist) {
		t.Errorf("the refused level was made: %v", err)
	}

	// chown: the home, the mount point and a tree that holds it.
	for _, p := range []string{h.home, mount} {
		_, err := h.s.chown(ctx, &ChownRequest{Path: p, Owner: me, Recursive: true})
		conflict("chown "+p, err)
	}
	_, err = h.s.chown(ctx, &ChownRequest{Path: bob, Owner: me, Recursive: true})
	passes("chown of another home", err)

	// user/ensure: a new account would get a home holding a mount point.
	withAccounts(t, testAccount{me, strconv.Itoa(os.Getuid()), strconv.Itoa(os.Getgid()), filepath.Join(h.www, me), []string{me}})
	_, err = h.s.ensureUnixUser(ctx, &EnsureUnixUserRequest{Login: "guest", Home: h.home, Shell: h.s.profile.NologinShell(), CreateHome: true, Groups: []string{sftpGroup}})
	conflict("useradd -m with that home", err)
	withAccounts(t, testAccount{me, strconv.Itoa(os.Getuid()), strconv.Itoa(os.Getgid()), filepath.Join(h.www, me), []string{me}},
		testAccount{"guest", "1500", "1500", h.home, []string{"guest", sftpGroup}})

	// user/remove: os.RemoveAll would go into the mounted folder; refused
	// before the account is touched.
	_, err = h.s.removeUnixUser(ctx, &RemoveUnixUserRequest{Login: "guest", RemoveHome: true, HomeUnder: h.www})
	conflict("removing the home", err)

	// acl/set: no write on the way, and no recursion over it.
	_, err = h.s.setACL(ctx, &SetACLRequest{Path: h.home, Entries: []string{"u:" + other + ":rwx"}})
	conflict("u:"+other+":rwx on the home", err)
	_, err = h.s.setACL(ctx, &SetACLRequest{Path: h.home, Entries: []string{"m::rwx"}})
	conflict("a mask with write on the home", err)
	_, err = h.s.setACL(ctx, &SetACLRequest{Path: h.home, Entries: []string{"d:o::rwx"}})
	conflict("a default entry with write on the home", err)
	_, err = h.s.setACL(ctx, &SetACLRequest{Path: h.home, Entries: []string{"g:" + other + ":r-x"}, Recursive: true})
	conflict("a recursive ACL over the home", err)
	_, err = h.s.siteACL(ctx, &SiteACLRequest{Root: h.home, Group: other})
	conflict("the web server's ACLs over the home", err)

	// paths/remove, symlink/ensure and file/ensure on the way.
	_, err = h.s.removePaths(ctx, &RemovePathsRequest{Paths: []string{mount}})
	conflict("removing the mount point", err)
	_, err = h.s.ensureSymlink(ctx, &EnsureSymlinkRequest{Path: mount, Target: "/etc", Owner: me})
	conflict("a symlink as the mount point", err)
	_, err = h.s.ensureFile(ctx, &EnsureFileRequest{Path: mount, Content: "x", Owner: me})
	conflict("a file as the mount point", err)
	if st, err := os.Lstat(mount); err != nil || !st.IsDir() {
		t.Fatalf("the mount point: %v %v", st, err)
	}
	_, err = h.s.ensureSymlink(ctx, &EnsureSymlinkRequest{Path: filepath.Join(bob, "link"), Target: "/tmp", Owner: me})
	passes("a symlink in another home", err)

	// An archive's directories get its modes: never into a tree that holds
	// the way to a mount point.
	plan, err := h.s.planTool(&toolCall{name: "tar", mode: modeStreamIn, args: []string{"--extract", "--file", "-", "--directory", h.home, "--no-same-owner"}})
	if err == nil {
		plan.close()
	}
	conflict("extracting into the home", err)
	plan, err = h.s.planTool(&toolCall{name: "tar", mode: modeStreamIn, args: []string{"--extract", "--file", "-", "--directory", bob, "--no-same-owner"}})
	passes("extracting into another home", err)
	if plan != nil {
		plan.close()
	}
	// The guard is released with the plan: a folder can be bound again.
	if _, err := h.bind(mount); err != nil {
		t.Fatalf("bind after the plans: %v", err)
	}
}

// The agent's record of a folder it bound guards the way to its mount point
// as a unit did: no other owner for the home, no removal of the mount point,
// until the folder is unbound.
func TestShareRecordGuardsTheWay(t *testing.T) {
	ctx := context.Background()
	h := newShareHost(t)
	other := otherAccount(t)
	mount := filepath.Join(h.home, "kaspy")
	mkdirs(t, mount)
	if _, err := h.bind(mount); err != nil {
		t.Fatal(err)
	}
	_, err := h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: h.home, Mode: 0o710, Owner: other}}})
	if agentStatus(err) != http.StatusConflict {
		t.Fatalf("the home to its account: %v, want 409", err)
	}
	if _, err := h.s.removePaths(ctx, &RemovePathsRequest{Paths: []string{mount}}); agentStatus(err) != http.StatusConflict {
		t.Fatalf("removing the mount point: %v, want 409", err)
	}
	if _, err := h.s.shareUnbind(ctx, &ShareUnbindRequest{Where: mount}); err != nil {
		t.Fatal(err)
	}
	if _, err := h.s.removePaths(ctx, &RemovePathsRequest{Paths: []string{mount}}); err != nil {
		t.Fatalf("removing the mount point once unbound: %v", err)
	}
}

// A call under a guard — an archive's extraction below the web root here —
// keeps a shared folder from being bound until it is done, but the other
// calls below the web root go on meanwhile: the bind gives up after a while
// instead of holding them back.
func TestShareUnitWaitsForGuardedCalls(t *testing.T) {
	ctx := context.Background()
	h := newShareHost(t)
	old := shareUnitWait
	shareUnitWait = 100 * time.Millisecond
	t.Cleanup(func() { shareUnitWait = old })
	mount := filepath.Join(h.home, "kaspy")
	mkdirs(t, mount)
	bob := filepath.Join(h.www, "bob")
	plan, err := h.s.planTool(&toolCall{name: "tar", mode: modeStreamIn, args: []string{"--extract", "--file", "-", "--directory", bob, "--no-same-owner"}})
	if err != nil {
		t.Fatal(err)
	}
	applied := make(chan error, 1)
	go func() {
		_, err := h.bind(mount)
		applied <- err
	}()
	done := make(chan error, 1)
	go func() {
		_, err := h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: filepath.Join(bob, "data"), Mode: 0o750}}})
		done <- err
	}()
	select {
	case err := <-done:
		if err != nil {
			t.Fatalf("dirs/ensure while the unit waits: %v", err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("dirs/ensure waits behind the unit")
	}
	if err := <-applied; agentStatus(err) != http.StatusServiceUnavailable {
		t.Fatalf("the bind during the extraction: %v, want 503", err)
	}
	if len(h.binds) != 0 {
		t.Fatalf("bound during the extraction: %v", h.binds)
	}
	plan.close()
	if _, err := h.bind(mount); err != nil {
		t.Fatalf("the bind after the extraction: %v", err)
	}
}

