// systemd keeps a mount unit whose file is gone as it was loaded, and mounts
// it when something that needs its mount point starts (an app's
// WorkingDirectory=, another folder's RequiresMountsFor=). So the removal of
// a shared folder's unit has systemd forget it while the guard still keeps
// the way root's — the unit's write lock is held across the reload — and a
// failed reload puts the file back: the way stays guarded as long as systemd
// may mount the folder.
func TestShareUnitRemovalForgetsIt(t *testing.T) {
	ctx := context.Background()
	h := newShareHost(t)
	mount := filepath.Join(h.home, "kaspy")
	mkdirs(t, mount)
	name, content := h.mountUnit(mount)
	unitFile := filepath.Join(h.s.unitDir, name)
	reloads := 0
	var reloadErr error
	old := reloadSystemd
	reloadSystemd = func(context.Context) error {
		reloads++
		if _, err := os.Stat(unitFile); !errors.Is(err, os.ErrNotExist) {
			t.Errorf("systemd reloads with the file still there: %v", err)
		}
		// the calls that change the way wait meanwhile
		if h.s.shareMu.TryRLock() {
			h.s.shareMu.RUnlock()
			t.Error("a guarded call could run while systemd still knows the unit")
		}
		return reloadErr
	}
	t.Cleanup(func() { reloadSystemd = old })
	writable := func() error {
		_, err := h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: []DirSpec{{Path: h.home, Mode: 0o770}}})
		return err
	}

	// A reload that fails: the unit is back, and the way stays guarded.
	h.placeUnit(t, mount)
	reloadErr = errors.New("systemd unreachable")
	if _, err := h.s.removeUnit(ctx, &RemoveUnitRequest{Name: name}); err == nil || !strings.Contains(err.Error(), "the unit is back") {
		t.Fatalf("remove with a failing reload: %v", err)
	}
	if got := readFileT(t, unitFile); got != content {
		t.Fatalf("the unit put back: %q", got)
	}
	if err := writable(); agentStatus(err) != http.StatusConflict {
		t.Fatalf("the home made writable while systemd may mount the folder: %v", err)
	}

	reloadErr = nil
	res, err := h.s.removeUnit(ctx, &RemoveUnitRequest{Name: name})
	if err != nil || !res.Removed {
		t.Fatalf("remove: %+v %v", res, err)
	}
	if reloads != 2 {
		t.Fatalf("systemd reloaded %d times, want once per removal", reloads)
	}
	if _, err := os.Stat(unitFile); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("the unit is still there: %v", err)
	}
	if err := writable(); err != nil {
		t.Fatalf("the home after the unit went: %v", err)
	}
	// Gone already: nothing to forget.
	if res, err := h.s.removeUnit(ctx, &RemoveUnitRequest{Name: name}); err != nil || res.Removed || reloads != 2 {
		t.Fatalf("a second removal: %+v %v (%d reloads)", res, err, reloads)
	}
	// Other units are removed as before, without the reload.
	fw := filepath.Join(h.s.unitDir, firewallUnitName)
	if err := os.WriteFile(fw, []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	if res, err := h.s.removeUnit(ctx, &RemoveUnitRequest{Name: firewallUnitName}); err != nil || !res.Removed || reloads != 2 {
		t.Fatalf("the firewall unit: %+v %v (%d reloads)", res, err, reloads)
	}
}

// A mount point with its folder mounted opens as the folder: dirs/ensure of
// the mount point — the API asks for it again whenever it applies a share,
// mp site fix too — leaves it alone instead of giving the site's folder
// root's owner and 0755. A mount point with nothing on it, or a mounted
// directory that is no shared folder's, gets the spec.
func TestEnsureDirsLeavesAMountedFolderAlone(t *testing.T) {
	ctx := context.Background()
	h := newShareHost(t)
	mount := filepath.Join(h.home, "kaspy")
	mkdirs(t, mount)
	h.placeUnit(t, mount)
	var mountedIno, homeIno uint64
	for p, ino := range map[string]*uint64{mount: &mountedIno, h.home: &homeIno} {
		var st unix.Stat_t
		if err := unix.Stat(p, &st); err != nil {
			t.Fatal(err)
		}
		*ino = st.Ino
	}
	mounted := true
	old := mountedOn
	mountedOn = func(fd int) bool {
		var st unix.Stat_t
		return mounted && unix.Fstat(fd, &st) == nil && (st.Ino == mountedIno || st.Ino == homeIno)
	}
	t.Cleanup(func() { mountedOn = old })
	// the folder's own mode, as the mount shows it
	chmods(t, map[string]uint32{mount: 0o2770, h.home: 0o710})
	spec := []DirSpec{{Path: h.home, Mode: 0o750}, {Path: mount, Mode: 0o755}}
	if _, err := h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: spec}); err != nil {
		t.Fatal(err)
	}
	if st, _ := os.Stat(mount); st.Mode()&(os.ModePerm|os.ModeSetgid) != 0o770|os.ModeSetgid {
		t.Fatalf("the mounted folder took the mount point's mode: %v", st.Mode())
	}
	if st, _ := os.Stat(h.home); st.Mode().Perm() != 0o750 {
		t.Fatalf("a mounted directory that is no mount point of a shared folder: %v", st.Mode())
	}
	mounted = false
	if _, err := h.s.ensureDirs(ctx, &EnsureDirsRequest{Dirs: spec}); err != nil {
		t.Fatal(err)
	}
	if st, _ := os.Stat(mount); st.Mode()&(os.ModePerm|os.ModeSetgid) != 0o755 {
		t.Fatalf("the mount point with nothing on it: %v", st.Mode())
	}
}
