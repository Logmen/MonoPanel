// A second command line is a ";" word as systemd splits words; a quoted or
// an escaped semicolon is an argument like any other.
func TestSingleCommand(t *testing.T) {
	for v, ok := range map[string]bool{
		`/usr/bin/node /var/www/alex/data/app/server.js --port=3000`: true,
		`/bin/sh -c "cd /var/www/alex/data ; exec ./run"`:            true,
		`/bin/sh -c 'cd /var/www/alex/data ; exec ./run'`:            true,
		`/usr/bin/find . -exec rm {} \;`:                             true,
		`/usr/bin/x a;b ;c`:                                          true,
		`/bin/sh -c "a \" ; b"`:                                      true,
		`/bin/true ; +/bin/sh -c id`:                                 false,
		"/bin/true\t;\t+/bin/sh -c id":                               false,
		`/bin/true ;`:                                                false,
		`/bin/x "quoted" ; +/bin/sh`:                                 false,
		`/bin/x a"b ; c"`:                                            false, // a quote inside a word: no quote to older systemd
		`+/bin/sh -c id`:                                             false,
		`"/bin/sh" -c id`:                                            false,
		` /bin/sh`:                                                   false,
	} {
		if err := singleCommand("ExecStart", v); (err == nil) != ok {
			t.Errorf("%q: %v, want ok=%v", v, err, ok)
		}
	}
	// The panel's app units with such a command pass whole.
	h := testUnitHost(t)
	unit := renderUnit(t, "systemd/app.service.tmpl", render.AppUnit{Login: "alex", Name: "sh", Command: `/bin/sh -c "cd /var/www/alex/data ; exec ./run"`, WorkDir: "/var/www/alex/data", Restart: "always", Binary: "/usr/bin/monopanel"})
	if err := CheckUnit("monopanel-app-alex-sh.service", []byte(unit), h); err != nil {
		t.Errorf("a quoted semicolon: %v\n%s", err, unit)
	}
}
