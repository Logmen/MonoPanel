// testUnitHost is a host where alex, bob and guest are panel accounts with
// their homes in /var/www, the Sphinx unit is EL's and nginx is
// nginx.service.
func testUnitHost(t *testing.T) *UnitHost {
	t.Helper()
	rel, _ := osprofile.ParseOSRelease(strings.NewReader("ID=almalinux\nID_LIKE=\"rhel centos fedora\"\nVERSION_ID=9.6\n"))
	el, err := osprofile.FromRelease(rel)
	if err != nil {
		t.Fatal(err)
	}
	return &UnitHost{
		WWWRoot: "/var/www", NginxService: "nginx.service", Sphinx: osprofile.Sphinx(el),
		ValkeyBinaries: []string{"/usr/bin/valkey-server", "/usr/bin/redis-server"},
		Account: func(login string) (*UnitAccount, error) {
			switch login {
			case "alex", "bob", "guest":
				return &UnitAccount{Login: login, Home: "/var/www/" + login, Group: login}, nil
			}
			return nil, errors.New("not a panel account")
		},
		SystemUser: func(login string) error {
			if login != "sphinx" {
				return errors.New("not a system account of its own")
			}
			return nil
		},
	}
}

func renderUnit(t *testing.T, tmpl string, data any) string {
	t.Helper()
	out, err := render.New("").Render(tmpl, data)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

