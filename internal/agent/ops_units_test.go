// Every unit the panel writes passes, as the API renders it.
func TestCheckUnitAcceptsThePanelsUnits(t *testing.T) {
	h := testUnitHost(t)
	for name, content := range panelUnits(t) {
		if err := CheckUnit(name, []byte(content), h); err != nil {
			t.Errorf("%s: %v\n%s", name, err, content)
		}
	}
	// An app without the panel's environment file, and one whose overridden
	// template still lists the variables in Environment= lines (the account's
	// own process gets them either way).
	plain := renderUnit(t, "systemd/app.service.tmpl", render.AppUnit{Login: "bob", Name: "bot", Command: "/usr/bin/python3 -m http.server", WorkDir: "/var/www/bob/data", Restart: "no", Binary: "/usr/bin/monopanel"})
	if err := CheckUnit("monopanel-app-bob-bot.service", []byte(plain), h); err != nil {
		t.Errorf("app without variables: %v\n%s", err, plain)
	}
	legacy := strings.Replace(plain, "Restart=no", "Environment=\"PORT=3000\"\nEnvironment=\"MODE=prod\"\nRestart=no", 1)
	if err := CheckUnit("monopanel-app-bob-bot.service", []byte(legacy), h); err != nil {
		t.Errorf("app with Environment= lines: %v", err)
	}
}

