// systemd's line rules, read the way systemd reads them.
func TestParseUnitLines(t *testing.T) {
	entries, err := parseUnit("# comment\n; also\n[Service]\n  User = alex  \nExecStart=/bin/a \\\n\t--b \\\\\nDescription=x \\\n\nKillMode=mixed\n")
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, e := range entries {
		got[e.key] = e.value
	}
	// A backslash at the end continues the line (read as a blank); an
	// escaped one does not; a continued line may end at a blank line.
	if got["User"] != "alex" || got["ExecStart"] != "/bin/a  \t--b \\\\" || got["Description"] != "x" || got["KillMode"] != "mixed" || len(entries) != 4 {
		t.Fatalf("%+v", entries)
	}
	if _, err := parseUnit("[Service]\nExecStart=/bin/a \\"); err == nil {
		t.Error("a file ending in a continued line was accepted")
	}
}

