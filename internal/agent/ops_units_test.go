// The units go where systemd reads them, root's 0644, the previous version
// to the history; the same content again changes nothing; removal takes the
// file.
func TestApplyAndRemoveUnit(t *testing.T) {
	ctx := context.Background()
	s, cl, dir := unitServer(t)
	units := panelUnits(t)
	for _, name := range []string{"monopanel-firewall.service", "nginx.service.d/monopanel.conf"} {
		res, err := cl.ApplyUnit(ctx, &ApplyUnitRequest{Name: name, Content: units[name], Origin: "test"})
		if err != nil || !res.Changed || res.Path != filepath.Join(dir, name) {
			t.Fatalf("%s: %+v %v", name, res, err)
		}
		if b, _ := os.ReadFile(res.Path); string(b) != units[name] {
			t.Fatalf("%s holds %q", name, b)
		}
		if st, _ := os.Stat(res.Path); st.Mode().Perm() != 0o644 {
			t.Fatalf("%s: mode %v", name, st.Mode())
		}
		if res, err := cl.ApplyUnit(ctx, &ApplyUnitRequest{Name: name, Content: units[name]}); err != nil || res.Changed {
			t.Fatalf("%s again: %+v %v", name, res, err)
		}
	}
	changed := strings.Replace(units["monopanel-firewall.service"], "Description=MonoPanel firewall", "Description=The firewall", 1)
	if _, err := cl.ApplyUnit(ctx, &ApplyUnitRequest{Name: "monopanel-firewall.service", Content: changed}); err != nil {
		t.Fatal(err)
	}
	hist := filepath.Join(s.cfg.ConfHistoryDir(), strings.TrimPrefix(filepath.Join(dir, "monopanel-firewall.service"), "/"))
	if entries, _ := os.ReadDir(hist); len(entries) != 1 {
		t.Fatalf("history: %v", entries)
	}
	res, err := cl.RemoveUnit(ctx, &RemoveUnitRequest{Name: "monopanel-firewall.service"})
	if err != nil || !res.Removed {
		t.Fatalf("remove: %+v %v", res, err)
	}
	if _, err := os.Stat(filepath.Join(dir, "monopanel-firewall.service")); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("the unit is still there")
	}
	if res, err := cl.RemoveUnit(ctx, &RemoveUnitRequest{Name: "monopanel-firewall.service"}); err != nil || res.Removed {
		t.Fatalf("remove again: %+v %v", res, err)
	}
}

// A refused unit leaves nothing behind; names that are not the panel's are
// refused for removal too.
func TestApplyUnitRefusals(t *testing.T) {
	ctx := context.Background()
	_, cl, dir := unitServer(t)
	evil := "[Service]\nExecStart=/bin/sh -c id\n[Install]\nWantedBy=multi-user.target\n"
	for _, name := range []string{"monopanel-firewall.service", "evil.service", "../evil.service", "monopanel-app-root-x.service"} {
		if _, err := cl.ApplyUnit(ctx, &ApplyUnitRequest{Name: name, Content: evil}); agentStatus(err) != http.StatusForbidden {
			t.Errorf("%s: %v, want 403", name, err)
		}
	}
	if entries, _ := os.ReadDir(dir); len(entries) != 0 {
		t.Fatalf("written: %v", entries)
	}
	for _, name := range []string{"sshd.service", "../../etc/passwd", "monopanel-agent.service", "etc.mount", ""} {
		if _, err := cl.RemoveUnit(ctx, &RemoveUnitRequest{Name: name}); agentStatus(err) != http.StatusForbidden {
			t.Errorf("remove %q: %v, want 403", name, err)
		}
	}
}

